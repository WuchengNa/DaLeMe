export function getTemplate(id) {
  return PLAN_TEMPLATES.find((template) => template.id === id) || null;
}

/** 模板概况：训练日 / 动作 / 总组数 / 预计时长（分钟） */
export function templateSummary(template) {
  const exercises = template.days.reduce((acc, d) => acc + d.exercises.length, 0);
  const sets = template.days.reduce(
    (acc, d) => acc + d.exercises.reduce((s, entry) => s + (Number(entry.sets) || 0), 0),
    0,
  );
  const seconds = template.days.reduce(
    (acc, d) => acc + d.exercises.reduce((s, entry) => s + (Number(entry.sets) || 0) * (45 + (Number(entry.rest) || 90)), 0),
    0,
  );
  return {
    days: template.days.length,
    exercises,
    sets,
    minutes: Math.round(seconds / Math.max(1, template.days.length) / 60),
  };
}

/** 把模板展开成一份可编辑的计划草稿（新 id，改完再保存） */
export function buildPlanDraft(template) {
  const planId = `plan_${uid('tpl')}`;
  return {
    id: planId,
    name: template.name,
    desc: template.desc,
    color: template.color || 'lime',
    createdAt: new Date().toISOString(),
    archived: false,
    days: template.days.map((d, i) => ({
      id: `${planId}_d${i + 1}`,
      name: d.name,
      short: d.short || `DAY ${i + 1}`,
      exercises: d.exercises.map((entry) => ({ ...entry })),
    })),
  };
}
